// Builds web/icons.js from the Reicon package (https://reicon.dev, MIT): only the icons listed here.
//   cd <scratch> && npm pack reicon@1.2.5 && tar xzf reicon-1.2.5.tgz
//   curl -sO https://reicon.dev/llms-icons.txt   (kebab -> PascalCase names)
//   node <panel>/scripts/icons.mjs <scratch> > <panel>/web/icons.js
// A name ending in "-f" takes the Filled weight; everything else is Outline.
import fs from 'fs';
import path from 'path';

const LIST = `
activity alert-triangle angle-down angle-left angle-right angle-up arrow-down arrow-left arrow-right arrow-rotate
arrow-up arrow-up-right bell bolt chat-round-dots check check-circle check-circle-f clock-circle close-square copy
copy-success cpu document-code download2 eye file file-pdf file-text file-zip fingerprint folder folder-open
gauge global hand hard-drive help-circle hierarchy hierarchy3 history image3 info-circle key keyboard
layers layers-alt list-check lock-keyhole maximize microchip minimize more-h paperclip pause3 pen people play-circle3
play3 plug plus power puzzle quote-up ram receipt-text row-horizontal search server shield-check slash-square
sidebar-left2 sparkle sparkle-f stop-f stopwatch terminal-square trash2 tuning upload2 wand-sparkle wave-pulse window2
x-circle x-circle-f xmark`.trim().split(/\s+/);

const dir = process.argv[2] || '.';
const pascal = Object.fromEntries(fs.readFileSync(path.join(dir, 'llms-icons.txt'), 'utf8').split('\n')
  .map((l) => l.match(/^- (\S+) -> (\S+)/)).filter(Boolean).map((m) => [m[1], m[2]]));

const out = [];
for (const name of LIST) {
  const filled = name.endsWith('-f');
  const base = filled ? name.slice(0, -2) : name;
  const src = fs.readFileSync(path.join(dir, 'package/icons', pascal[base] + '.js'), 'utf8');
  const m = src.match(new RegExp(`${filled ? 'F' : 'O'}: \`([^\`]*)\``));
  if (!m) throw new Error(`no ${filled ? 'Filled' : 'Outline'} data for ${base}`);
  if (/\bid="/.test(m[1])) throw new Error(`${name} uses ids (clip paths): pick another icon`);
  out.push(`  '${name}': '${m[1].replace(/\s+/g, ' ').replace(/'/g, "\\'")}',`);
}

process.stdout.write(`'use strict';
// Reicon icons (https://reicon.dev, MIT licence), generated by scripts/icons.mjs: add names to its list.
// One hidden sprite of <symbol>s; ic(name) references it, so a chat with hundreds of rows stays light.
const ICONS = {
${out.join('\n')}
};

(() => {
  const s = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  s.setAttribute('class', 'isprite');
  s.setAttribute('aria-hidden', 'true');
  s.innerHTML = Object.entries(ICONS).map(([n, d]) => \`<symbol id="i-\${n}" viewBox="0 0 24 24" fill="none">\${d}</symbol>\`).join('');
  document.body.prepend(s);
})();

const ic = (name, cls = '') => \`<svg class="i\${cls ? ' ' + cls : ''}" aria-hidden="true"><use href="#i-\${name}"/></svg>\`;
`);
